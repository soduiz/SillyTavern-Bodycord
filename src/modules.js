export const XENO_CLASS_HUMAN = '人类';

// 把「另一个亲代属于哪一边」那格的自由文本解析成"哪几边"。
//
// 这一格的解析只做这一份，两处共用 ——
//   prompt.js 用它决定"发哪张异种表"，store.js 用它决定"这份答案到底用不用得上"。
//   为什么单抽一个函数：store.js 不能引 prompt.js（会成环），而 modules.js 是叶子模块，谁都能引。
//
// 返回 { kind, sides }：
//   kind 为 sides   —— sides 是 east / west 的组合，两边都有就是混血那种
//   kind 为 human   —— 明确在说人类（含「人类（类人形）」这类带修饰的写法）
//   kind 为 unknown —— 没写、或认不出（调用方：既不参与门控，也别当成"已报过"，下轮接着问）
//
// 三条口径（都是踩过的坑）：
//   一、两边都出现时用两个独立判断，绝不写 else if —— 写了 else 会静默吞掉后一边，
//       混血那种又会退化成只发一张表。
//   二、模型要是直接报了大类名（鬼系 / 尸族 / 器物与灵体 / 非生物…）也得认得出，
//       不然它明明说对了、却被判成"没交代"，那张表永远发不出去。
//   三、判断"在说人类"要放在兜底关键词之前 —— 不然「人类（类人形）」会被兜底里的
//       「类人」命中、判成西边。
// 注意：本文件的注释也受守卫扫（不许出现星号加粗与反引号）⇒ 统一用行注释。
export function parseXenoSideAnswer(raw) {
    const s = String(raw ?? '').trim();
    if (!s) return { kind: 'unknown', sides: [] };
    const out = [];
    const push = (v) => { if (!out.includes(v)) out.push(v); };
    // 三：先判"这是在说人类"（带修饰也算）
    if (s.includes(XENO_CLASS_HUMAN) && !s.includes('东方') && !s.includes('西方')) {
        return { kind: 'human', sides: [] };
    }
    // 分隔符放宽（间隔号 / 加号 / 空白都当分隔）；「和」「与」不切开，
    //   靠下面"两个独立判断"就能同时认出两边 ✓
    for (const part of s.split(/[、,，/|·+＋\s]+/).map((x) => x.trim()).filter(Boolean)) {
        if (part === XENO_CLASS_HUMAN) continue;
        if (part.includes('东西混血')) { push('east'); push('west'); continue; }
        const isEast = part.includes('东方') || XENO_CLASSES_EAST.includes(part);
        const isWest = part.includes('西方') || (!isEast && XENO_CLASSES.includes(part));
        if (isEast) push('east');
        if (isWest) push('west');
    }
    if (out.length) return { kind: 'sides', sides: out };
    // 兜底：整串拿两份互斥关键词再判一次（同样是两个独立判断，两边都查）
    if (XENO_EAST_HINTS.some((kw) => s.includes(kw))) push('east');
    if (XENO_WEST_HINTS.some((kw) => s.includes(kw))) push('west');
    if (out.length) return { kind: 'sides', sides: out };
    return { kind: 'unknown', sides: [] };
}

